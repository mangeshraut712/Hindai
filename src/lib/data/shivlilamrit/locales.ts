export function kathaParagraphs(
  katha: ChapterKatha,
  locale: ReaderLocale,
  chapterId?: ChapterId,
  extraSlug?: string
): string[] {
  switch (locale) {
    case "mr":
      return katha.mr;
    case "en":
      return katha.en;
    case "hi":
      if (chapterId) {
        return CHAPTER_KATHA_HI[chapterId];
      }
      if (extraSlug && EXTRA_KATHA_HI[extraSlug]) {
        return EXTRA_KATHA_HI[extraSlug];
      }
      return katha.hi ?? katha.mr;
    case "roman":
      return katha.mr.map((para) => transliterateToIast(para));
    default: {
      const _exhaustive: never = locale;
      return _exhaustive;
    }
  }
}

export function oviDisplay(text: string, locale: ReaderLocale): string {
  switch (locale) {
    case "mr":
    case "hi":
      return text;
    case "en":
    case "roman":
      return transliterateToIast(text);
    default: {
      const _exhaustive: never = locale;
      return _exhaustive;
    }
  }
}
